-- Run this in Supabase SQL Editor to enable the optional birthday message form.
-- Messages are insert-only from the public website. Read them in Supabase Table Editor.
create table if not exists public.valu_messages (
  id bigint generated by default as identity primary key,
  wish text,
  adventure text,
  message text,
  created_at timestamptz not null default now()
);

alter table public.valu_messages enable row level security;

-- Remove older policies with the same names before recreating them.
drop policy if exists "Anyone can send a birthday message" on public.valu_messages;
drop policy if exists "No public reads" on public.valu_messages;

create policy "Anyone can send a birthday message"
on public.valu_messages
for insert
to anon
with check (
  (wish is null or char_length(wish) <= 3000) and
  (adventure is null or char_length(adventure) <= 3000) and
  (message is null or char_length(message) <= 5000)
);

